#!/usr/bin/env python3
"""Generate native/recomp/sh2_decode_table.h from saturn-recomp's SH-2 decode table.

The C++ interpreter and the on-console generator decode with the same table as
src/saturnrecomp/sh2.py (MIT, saturn-recomp), so the two can never disagree.
The output contains opcode patterns only: no game data.

    python3 tools/ps5/gen-sh2-decode.py --framework .local/saturn-recomp
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]


def ident(fmt):
    s = fmt.replace("@-", " pre_").replace("+", "_post").replace("#imm", "imm").replace("@T", "pc")
    s = s.replace("/", "_").replace(".", "_").replace("@", "at_")
    return "OP_" + re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--framework", default=str(ROOT / ".local/saturn-recomp"))
    ap.add_argument("--out", default=str(ROOT / "native/recomp/sh2_decode_table.h"))
    a = ap.parse_args()
    sys.path.insert(0, str(pathlib.Path(a.framework) / "src"))
    from saturnrecomp import sh2  # noqa: E402

    fmts = []
    for mask, val, op, fmt, kind, nsh, msh in sh2._TABLE:
        if fmt not in fmts:
            fmts.append(fmt)
    names = [ident(f) for f in fmts]
    assert len(set(names)) == len(names), "identifier clash"
    out = ["// Generated by tools/ps5/gen-sh2-decode.py from saturn-recomp src/saturnrecomp/sh2.py (MIT).",
           "// Opcode patterns only. Do not edit; regenerate.", "#pragma once", "#include <cstdint>", "",
           "namespace sf3 {", "enum Sh2Op : uint8_t {", "    OP_INVALID = 0,"]
    out += ["    %s," % n for n in names]
    out += ["    OP_COUNT", "};", "",
            "struct Sh2Pattern { uint16_t mask, value; Sh2Op op; bool delay; };",
            "// Most specific first, the order sh2.py matches in.",
            "inline constexpr Sh2Pattern kSh2Patterns[] = {"]
    for mask, val, op, fmt, kind, nsh, msh in sh2._TABLE:
        out.append("    {0x%04X, 0x%04X, %s, %s},  // %s" % (mask, val, ident(fmt), "true" if "delay" in kind.split() else "false", fmt))
    out += ["};", "", "inline constexpr const char* kSh2OpFormat[OP_COUNT] = {", '    ".word",']
    out += ['    "%s",' % f for f in fmts]
    out += ["};", "",
            "// Bit position of Rn and Rm in the word for each op (255: the op has none).",
            "struct Sh2Fields { uint8_t n_shift, m_shift; };",
            "inline constexpr Sh2Fields kSh2Fields[OP_COUNT] = {", "    {255, 255},"]
    seen = {}
    for mask, val, op, fmt, kind, nsh, msh in sh2._TABLE:
        seen.setdefault(fmt, (255 if nsh is None else nsh, 255 if msh is None else msh))
    out += ["    {%d, %d},  // %s" % (seen[f] + (f,)) for f in fmts]
    out += ["};", "}  // namespace sf3", ""]
    pathlib.Path(a.out).write_text("\n".join(out))
    print("wrote %s: %d patterns, %d ops" % (a.out, len(sh2._TABLE), len(fmts)))


if __name__ == "__main__":
    main()
